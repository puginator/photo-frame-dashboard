// Regenerates js/would-you-rather.js from the Crazy Thoughts app's daily questions.
//
//   gh api repos/puginator/crazy_thoughts/contents/src/data/daily_questions.ts \
//     -H "Accept: application/vnd.github.raw" > /tmp/daily_questions.ts
//   node scripts/export-wyr.mjs /tmp/daily_questions.ts
//
// The source is a 366-slot calendar laid out on a leap year (slot 305 = Oct 31). A question that
// appears in exactly one slot is tied to that date (holidays, Halloween...); the rest are seasonal
// fillers repeated for ~80 days. We keep each distinct question once, key the one-day ones by
// MM-DD, and let the dashboard rotate through all of them on other days.
import { readFileSync, writeFileSync } from 'node:fs';

var src = readFileSync(process.argv[2], 'utf8');
var list = JSON.parse(src.slice(src.indexOf('= [') + 2, src.lastIndexOf(']') + 1));
var SAFE = ['all', 'kids', 'family']; // AgeRating values that are fine for a family surface
var kept = list.filter(function (q) { return !q.ageRating || SAFE.indexOf(q.ageRating) > -1; });
var excluded = list.length - kept.length;

var byText = new Map();
list.forEach(function (q, i) {
  if (kept.indexOf(q) < 0) return;
  var key = q.optionA.text + '\u0000' + q.optionB.text;
  if (!byText.has(key)) byText.set(key, { a: q.optionA.text, b: q.optionB.text, slots: [] });
  byText.get(key).slots.push(i);
});
var all = [], dated = {};
byText.forEach(function (q) {
  all.push([q.a, q.b]);
  if (q.slots.length === 1) {
    var d = new Date(2024, 0, 1 + q.slots[0]); // leap year, matching the source layout
    dated[('0' + (d.getMonth() + 1)).slice(-2) + '-' + ('0' + d.getDate()).slice(-2)] = all.length - 1;
  }
});

writeFileSync(new URL('../js/would-you-rather.js', import.meta.url),
  '// Generated by scripts/export-wyr.mjs from puginator/crazy_thoughts src/data/daily_questions.ts. Do not edit.\n' +
  '// ' + list.length + ' source slots, ' + all.length + ' distinct questions. Kid-safe filter (ageRating): ' + excluded +
  ' excluded; no source entry sets ageRating, and all were reviewed by hand.\n' +
  '// all: [optionA, optionB]; dated: MM-DD -> index into all.\n' +
  'export default ' + JSON.stringify({ all: all, dated: dated }, null, 1) + ';\n');
console.log(all.length + ' questions, ' + Object.keys(dated).length + ' dated, ' + excluded + ' excluded');
